"""Export the wire types' JSON Schema and the API prefix to the frontend: `make schema`.

The frontend mirrors these types by hand in `frontend/src/api/`; the committed
`schema.json` lets tests on both sides catch drift.
"""

import json

from rag_hive.agents.topology import RunGraph
from rag_hive.api import API_PREFIX
from rag_hive.api.health import HealthResponse
from rag_hive.config import REPO_ROOT
from rag_hive.events.schema import agent_event_adapter

SCHEMA_PATH = REPO_ROOT / "frontend" / "src" / "api" / "schema.json"
"""Committed location of the exported schema."""


def render_wire_schema() -> str:
    """Return the wire schema as stable, pretty-printed JSON (with a trailing newline)."""
    schema = {
        "$comment": "Generated by `make schema` (python -m rag_hive.schema). Do not edit.",
        "apiPrefix": API_PREFIX,
        "AgentEvent": agent_event_adapter.json_schema(mode="serialization", by_alias=True),
        "RunGraph": RunGraph.model_json_schema(mode="serialization", by_alias=True),
        "HealthResponse": HealthResponse.model_json_schema(mode="serialization", by_alias=True),
    }
    return json.dumps(schema, indent=2, sort_keys=True) + "\n"


def main() -> None:
    """Write the schema to `SCHEMA_PATH`."""
    SCHEMA_PATH.parent.mkdir(parents=True, exist_ok=True)
    SCHEMA_PATH.write_text(render_wire_schema(), encoding="utf-8")


if __name__ == "__main__":
    main()
