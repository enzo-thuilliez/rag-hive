"""Export JSON Schemas: `make schema`.

- The wire types and the API prefix go to `frontend/src/api/schema.json`. The frontend mirrors
  these types by hand in `frontend/src/api/`; the committed file lets tests on both sides catch
  drift.
- The data models of hand-written files (`CorpusEntry`, `CorpusManifest`, `GoldenQuestion`) go
  to `docs/schemas/`, one file each, for editors and other tools that validate the YAML.
"""

import json
from pathlib import Path

from pydantic import BaseModel

from rag_hive.agents.topology import RunGraph
from rag_hive.api import API_PREFIX
from rag_hive.api.health import HealthResponse
from rag_hive.config import REPO_ROOT
from rag_hive.corpus.models import CorpusEntry, CorpusManifest
from rag_hive.evaluation.golden import GoldenQuestion
from rag_hive.events.schema import agent_event_adapter

SCHEMA_PATH = REPO_ROOT / "frontend" / "src" / "api" / "schema.json"
"""Committed location of the exported wire schema."""

DATA_SCHEMA_DIR = REPO_ROOT / "docs" / "schemas"
"""Committed location of the data model schemas."""

DATA_MODELS: dict[str, type[BaseModel]] = {
    "corpus-entry.schema.json": CorpusEntry,
    "corpus-manifest.schema.json": CorpusManifest,
    "golden-question.schema.json": GoldenQuestion,
}
"""Data models exported to `DATA_SCHEMA_DIR`, by file name."""

_GENERATED = "Generated by `make schema` (python -m rag_hive.schema). Do not edit."


def render_wire_schema() -> str:
    """Return the wire schema as stable, pretty-printed JSON (with a trailing newline)."""
    schema = {
        "$comment": _GENERATED,
        "apiPrefix": API_PREFIX,
        "AgentEvent": agent_event_adapter.json_schema(mode="serialization", by_alias=True),
        "RunGraph": RunGraph.model_json_schema(mode="serialization", by_alias=True),
        "HealthResponse": HealthResponse.model_json_schema(mode="serialization", by_alias=True),
    }
    return json.dumps(schema, indent=2, sort_keys=True) + "\n"


def render_data_schemas() -> dict[Path, str]:
    """Return each data model's JSON Schema (validation mode), keyed by its output path."""
    rendered: dict[Path, str] = {}
    for file_name, model in DATA_MODELS.items():
        schema = {"$comment": _GENERATED, **model.model_json_schema(mode="validation")}
        rendered[DATA_SCHEMA_DIR / file_name] = json.dumps(schema, indent=2, sort_keys=True) + "\n"
    return rendered


def main() -> None:
    """Write the wire schema to `SCHEMA_PATH` and the data schemas to `DATA_SCHEMA_DIR`."""
    outputs = {SCHEMA_PATH: render_wire_schema(), **render_data_schemas()}
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
